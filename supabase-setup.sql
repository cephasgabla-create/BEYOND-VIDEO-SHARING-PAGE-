drop policy if exists "Anyone can view Beyond media" on storage.objects;
create policy "Anyone can view Beyond media"
on storage.objects for select to anon, authenticated
using (bucket_id = 'videos');

drop policy if exists "Users upload media to own folder" on storage.objects;
create policy "Users upload media to own folder"
on storage.objects for insert to authenticated
with check (
  bucket_id = 'videos'
  and (storage.foldername(name))[1] = (select auth.uid())::text
);

drop policy if exists "Users update media in own folder" on storage.objects;
create policy "Users update media in own folder"
on storage.objects for update to authenticated
using (
  bucket_id = 'videos'
  and (storage.foldername(name))[1] = (select auth.uid())::text
)
with check (
  bucket_id = 'videos'
  and (storage.foldername(name))[1] = (select auth.uid())::text
);

drop policy if exists "Users delete media in own folder" on storage.objects;
create policy "Users delete media in own folder"
on storage.objects for delete to authenticated
using (
  bucket_id = 'videos'
  and (storage.foldername(name))[1] = (select auth.uid())::text
);

-- 14. REALTIME
-- Adds the four core tables to Supabase Realtime if they are not present.
do $$
declare
  table_name text;
begin
  foreach table_name in array array['videos', 'likes', 'comments', 'follows']
  loop
    if not exists (
      select 1
      from pg_publication_tables
      where pubname = 'supabase_realtime'
        and schemaname = 'public'
        and tablename = table_name
    ) then
      execute format(
        'alter publication supabase_realtime add table public.%I',
        table_name
      );
    end if;
  end loop;
end $$;

-- 15. CREATE/ENSURE THE SIGNED-IN USER'S PROFILE
create or replace function public.ensure_beyond_profile(
  requested_username text,
  requested_display_name text
)
returns jsonb
language plpgsql
set search_path = ''
as $function$
declare
  current_user_id uuid := auth.uid();
  user_email text := auth.jwt() ->> 'email';
  user_metadata jsonb :=
    coalesce(auth.jwt() -> 'user_metadata', '{}'::jsonb);
  base_username text;
  safe_username text;
  chosen_display_name text;
begin
  if current_user_id is null then
    raise exception 'Authentication is required.';
  end if;

  base_username := lower(coalesce(
    nullif(trim(requested_username), ''),
    nullif(user_metadata ->> 'username', ''),
    split_part(coalesce(user_email, 'beyond_user'), '@', 1)
  ));

  safe_username := left(
    regexp_replace(base_username, '[^a-z0-9._-]', '', 'g'),
    30
  );

  if length(safe_username) < 3 then
    safe_username := 'user_' ||
      substr(replace(current_user_id::text, '-', ''), 1, 8);
  end if;

  -- Use a stable user-specific suffix if the username is already taken.
  if exists (
    select 1
    from public.profiles p
    where p.username = safe_username
      and p.id <> current_user_id
  ) then
    safe_username := left(safe_username, 21) || '_' ||
      substr(replace(current_user_id::text, '-', ''), 1, 8);
  end if;

  chosen_display_name := coalesce(
    nullif(trim(requested_display_name), ''),
    nullif(user_metadata ->> 'display_name', ''),
    safe_username
  );

  insert into public.profiles (id, username, display_name)
  values (current_user_id, safe_username, chosen_display_name)
  on conflict (id) do update
    set username = coalesce(public.profiles.username, excluded.username),
        display_name = coalesce(
          nullif(public.profiles.display_name, ''),
          excluded.display_name
        );

  return jsonb_build_object(
    'id', current_user_id,
    'username', safe_username
  );
end;
$function$;

create or replace function public.ensure_beyond_profile()
returns jsonb
language sql
set search_path = ''
as $function$
  select public.ensure_beyond_profile(null::text, null::text);
$function$;

revoke all on function public.ensure_beyond_profile(text, text) from public;
revoke all on function public.ensure_beyond_profile() from public;

grant execute on function public.ensure_beyond_profile(text, text)
to authenticated;

grant execute on function public.ensure_beyond_profile()
to authenticated;

commit;

