
-- BEYOND: CORE SUPABASE DATABASE SETUP
-- Supports profiles, videos, follows, likes, comments, storage and realtime.
-- Review existing policies and schema before running on an existing database.

begin;

create extension if not exists pgcrypto;

-- 1. PROFILES
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique,
  display_name text,
  bio text not null default '',
  avatar_url text,
  banner_url text,
  accent_color text not null default '#ff2d55',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- 2. VIDEOS
create table if not exists public.videos (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  video_url text not null,
  caption text not null default '',
  hashtags text not null default '',
  status text not null default 'published'
    check (status in ('draft', 'published', 'private')),
  views_count bigint not null default 0 check (views_count >= 0),
  likes_count bigint not null default 0 check (likes_count >= 0),
  created_at timestamptz not null default now()
);

-- 3. FOLLOWS
create table if not exists public.follows (
  follower_id uuid not null references auth.users(id) on delete cascade,
  following_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (follower_id, following_id),
  check (follower_id <> following_id)
);

-- 4. LIKES
create table if not exists public.likes (
  user_id uuid not null references auth.users(id) on delete cascade,
  video_id uuid not null references public.videos(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, video_id)
);

-- 5. COMMENTS
create table if not exists public.comments (
  id bigint generated by default as identity primary key,
  video_id uuid not null references public.videos(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  content text not null
    check (char_length(trim(content)) between 1 and 1000),
  hidden_by_creator boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.comments
  add column if not exists hidden_by_creator boolean not null default false;

-- 6. INDEXES
create index if not exists videos_published_created_idx
  on public.videos (created_at desc)
  where status = 'published';

create index if not exists videos_user_created_idx
  on public.videos (user_id, created_at desc);

create index if not exists follows_following_idx
  on public.follows (following_id);

create index if not exists likes_video_idx
  on public.likes (video_id);

create index if not exists comments_video_created_idx
  on public.comments (video_id, created_at desc);

-- 7. ENABLE ROW LEVEL SECURITY
alter table public.profiles enable row level security;
alter table public.videos enable row level security;
alter table public.follows enable row level security;
alter table public.likes enable row level security;
alter table public.comments enable row level security;

-- 8. PROFILE POLICIES
drop policy if exists "Profiles are readable" on public.profiles;
create policy "Profiles are readable"
on public.profiles for select to anon, authenticated
using (true);

drop policy if exists "Users create own profile" on public.profiles;
create policy "Users create own profile"
on public.profiles for insert to authenticated
with check (auth.uid() = id);

drop policy if exists "Users update own profile" on public.profiles;
create policy "Users update own profile"
on public.profiles for update to authenticated
using (auth.uid() = id)
with check (auth.uid() = id);

-- 9. VIDEO POLICIES
drop policy if exists "Published videos are readable" on public.videos;
create policy "Published videos are readable"
on public.videos for select to anon, authenticated
using (status = 'published' or auth.uid() = user_id);

drop policy if exists "Users create own videos" on public.videos;
create policy "Users create own videos"
on public.videos for insert to authenticated
with check (auth.uid() = user_id);

drop policy if exists "Users update own videos" on public.videos;
create policy "Users update own videos"
on public.videos for update to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

drop policy if exists "Users delete own videos" on public.videos;
create policy "Users delete own videos"
on public.videos for delete to authenticated
using (auth.uid() = user_id);

-- 10. FOLLOW POLICIES
drop policy if exists "Follows are readable" on public.follows;
create policy "Follows are readable"
on public.follows for select to anon, authenticated
using (true);

drop policy if exists "Users follow as themselves" on public.follows;
create policy "Users follow as themselves"
on public.follows for insert to authenticated
with check (
  auth.uid() = follower_id
  and follower_id <> following_id
);

drop policy if exists "Users unfollow as themselves" on public.follows;
create policy "Users unfollow as themselves"
on public.follows for delete to authenticated
using (auth.uid() = follower_id);

-- 11. LIKE POLICIES
drop policy if exists "Likes are readable" on public.likes;
create policy "Likes are readable"
on public.likes for select to anon, authenticated
using (true);

drop policy if exists "Users like as themselves" on public.likes;
create policy "Users like as themselves"
on public.likes for insert to authenticated
with check (
  auth.uid() = user_id
  and exists (
    select 1 from public.videos v
    where v.id = video_id
      and v.status = 'published'
  )
);

drop policy if exists "Users remove own likes" on public.likes;
create policy "Users remove own likes"
on public.likes for delete to authenticated
using (auth.uid() = user_id);

-- 12. COMMENT POLICIES
drop policy if exists "Comments are readable" on public.comments;
create policy "Comments are readable"
on public.comments for select to anon, authenticated
using (
  exists (
    select 1
    from public.videos v
    where v.id = comments.video_id
      and (
        v.status = 'published'
        or v.user_id = (select auth.uid())
      )
      and (
        comments.hidden_by_creator = false
        or v.user_id = (select auth.uid())
      )
  )
);

drop policy if exists "Signed in users add own comments" on public.comments;
create policy "Signed in users add own comments"
on public.comments for insert to authenticated
with check (
  auth.uid() = user_id
  and exists (
    select 1 from public.videos v
    where v.id = video_id
      and v.status = 'published'
  )
);

drop policy if exists "Users delete own comments" on public.comments;
create policy "Users delete own comments"
on public.comments for delete to authenticated
using (auth.uid() = user_id);

-- Only the owner of the video can hide/unhide its comments.
drop policy if exists "Video owners hide comments" on public.comments;
create policy "Video owners hide comments"
on public.comments for update to authenticated
using (
  exists (
    select 1 from public.videos v
    where v.id = comments.video_id
      and v.user_id = (select auth.uid())
  )
)
with check (
  exists (
    select 1 from public.videos v
    where v.id = comments.video_id
      and v.user_id = (select auth.uid())
  )
);

